def _atlas_identity(result) -> dict[str, object] | None:
    """The coordinate system this report's coverage numbers were measured in.

    Returns None when the scan placed nothing, so the footer says nothing rather
    than naming an atlas that produced no numbers.
    """
    cov = (result.ctx.stats or {}).get("atlas_coverage") or {}
    if not cov.get("atlas_version"):
        return None
    return {
        "version": cov.get("atlas_version", ""),
        "pipeline_hash": cov.get("pipeline_hash", "") or "",
        "encoder_weight_hash": cov.get("encoder_weight_hash", "") or "",
        "embed_model": cov.get("embed_model", "") or "",
        "normalization_variant": cov.get("normalization_variant") or "",
        "n_l1": cov.get("n_l1"),
        "n_regions": cov.get("regions_total"),
    }


def _tokens_short(count: int | None) -> str:
    if not count:
        return "—"
    if count >= 1_000_000_000:
        return f"{count / 1e9:.1f}B"
    if count >= 1_000_000:
        return f"{count / 1e6:.1f}M"
    if count >= 1_000:
        return f"{count / 1e3:.0f}k"
    return f"{count:,}"


def render(
    result: ScanResult,
    fp: Fingerprint,
    budget: Any = None,
    *,
    include_evidence: bool = True,
    summary: ScanSummary | None = None,
) -> str:
    env = Environment(autoescape=True, undefined=StrictUndefined,
                      trim_blocks=True, lstrip_blocks=True)
    template = env.from_string(_TEMPLATE)
    s = summary or build(result, budget=budget, include_evidence=include_evidence)

    for problem in (*s.problems, *s.notes):
        for ev in problem.evidence:
            ev.excerpt = safe_snippet(ev.excerpt)
            if ev.partner_excerpt:
                ev.partner_excerpt = safe_snippet(ev.partner_excerpt)

    overlap: list[dict] = []
    for problem in s.problems + s.notes:
        if problem.check_id == "T1-OVERLAP-001":
            for finding in result.findings:
                if finding.check_id == "T1-OVERLAP-001":
                    overlap = finding.data.get("matrix", [])[:20]

    seen: set[str] = set()
    skipped = []
    for entry in result.skipped:
        if entry.reason in seen:
            continue
        seen.add(entry.reason)
        skipped.append(entry)

    off = (s.atlas.off_detail if s.atlas else {}) or {}
    off_examples = []
    if include_evidence and s.atlas:
        for ex in s.atlas.off_examples[:4]:
            off_examples.append({
                "score": float(ex.get("score", 0.0)),
                "excerpt": safe_snippet(
                    str(ex.get("excerpt", "")).replace("\n", " "), 160
                ),
            })

    # "Estimated from a sample" with no interval on it tells a reader the number
    # is soft and gives them nothing to do about it. The interval is the whole
    # of what that sentence was for, so the caption appears only when there is
    # one to print.
    has_tokenizer = result.ctx.tokenizer is not None
    token_note = ""
    if s.tokens and has_tokenizer:
        token_note = "counted exactly"
    elif s.tokens and s.token_margin:
        token_note = f"estimated, ±{s.token_margin * 100:.2f}%"

    root = result.ctx.root
    return template.render(
        css=stylesheet(),
        logo=TEXT_LOGO_SVG,
        ratio=density_ratio,
        gradient=gradient(),
        s=s,
        c=s.composition,
        problems=s.problems,
        notes=s.notes,
        root=root,
        root_short=root.rstrip("/").split("/")[-1] or root,
        tokens_short=_tokens_short(s.tokens),
        token_note=token_note,
        datasets=fp.datasets,
        overlap=overlap,
        budget=budget_rows(budget),
        budget_method=budget_method(budget, exact=has_tokenizer),
        budget_notes=list(getattr(budget, "notes", []) or []),
        has_tokenizer=has_tokenizer,
        skipped=skipped,
        degradations=result.ctx.degradations,
        provenance=sorted(fp.provenance.items()),
        fingerprint_id=fp.fingerprint_id,
        pipeline_version=fp.pipeline_version,
        # A coverage number means nothing without the coordinate system it was
        # measured in. The fingerprint has carried these since v1; the report a
        # person actually reads and forwards did not.
        atlas_id=_atlas_identity(result),
        includes_evidence=include_evidence,
        shards=int(result.ctx.stats.get("shards", 1) or 1),
        off=off,
        off_by_dataset=sorted(
            ((k, v) for k, v in (off.get("by_dataset") or {}).items()),
            key=lambda kv: -kv[1]["rate"],
        )[:4],
        off_examples=off_examples,
    )
