"""Self-contained HTML report.

One file, no network, no CDN, no web fonts, opens from ``file://``. That matters
because the users this was built for work on clusters where standing up a server
and forwarding a port is awkward: a single file can be produced inside a batch
job and copied with ``scp`` when policy permits. By default it contains record
excerpts; ``--no-evidence`` removes excerpts and source locations.

Autoescaping is on unconditionally and every corpus string additionally passes
through :func:`safe_snippet`, because everything rendered here came from data we
did not write.

**The page describes before it complains.** It used to open with a list of
findings, which meant a reader who had just been handed a folder learned what
was wrong with it before learning what it was — and learned what it was only by
inference, since a finding mentions a property of the corpus exactly when that
property is broken. So composition comes first: what language, what shape,
whether it is already formatted, how big.

Then the findings, then the token budget, then the map. That order is what a
person actually asks in sequence: what is this, what is wrong with it, what will
it cost, and what is it missing. The one-line verdict sits at the head of the
findings rather than at the head of the page: the sentence it carries is a count
of what is directly below it and a name for the worst of them, which is a
caption for that list and was a verdict on a corpus the reader had not been
shown yet.

**Sections carry no standfirst.** Every one of them had a paragraph under its
title explaining what the section was about, and each was true, and together
they were four screens of prose a reader scrolled past to reach the numbers —
which taught them to scroll past the notes that were not throat-clearing.
Anything that has to be said now sits inside the card it is about.

What the page must not do is present the atlas's own labels as facts about the
data. See :mod:`dropoutt.report.summary` for why, and for the rule that a place
on the map is named by the reader's own record before it is named by a caption.

The one thing on this page that is not text or a bar is the density grid, and
its whole design follows from the CSP three lines below: no script, ever. So it
has no sort control and no tooltips — every cell prints its own ratio, which is
also what makes it survive a printer and a screenshot. See
:func:`dropoutt.report.atlas_story._grid`.
"""

